-- ════════════════════════════════════════════════════════════════
-- [기록] 재고이동 "취소" 건 — 롯데백화점 미아점 → 그린푸드 현대 미아점 (2026-11-05)
--   침향환골드(HS_한생방침향환(25%)) / 침향환프리미엄(HS_한생방침향환프리미엄)
-- ════════════════════════════════════════════════════════════════
-- [최종 결론] 그 재고이동은 '전부 실패'였다.
--   · store_transfers 에 오늘자 이동기록 없음 (insert 미반영)
--   · 출발매장(롯데 미아점) 재고 차감도 실제로 일어나지 않았음 (원래 12 그대로)
--   → 즉 취소할 대상 자체가 없었다.
--
-- [경위 메모] 조사 중 updated_at(06:57) 을 '차감됨'으로 오인하여 +2 복구를 한 번
--   실행(12→14) 했다가, 실제 원래 수량이 12임을 확인하고 12 로 되돌려 정리함.
--   최종 상태: 두 상품 모두 stock_qty = 12 (정상).
--
-- 이 파일은 더 이상 실행할 UPDATE 가 없다(기록용). 재고 확인만 남긴다.
-- ════════════════════════════════════════════════════════════════

-- 현재 상태 확인 (둘 다 12 이면 정상)
select store_name, branch_name, product_name, stock_qty, updated_at
from public.store_stock
where store_name='롯데백화점' and branch_name='미아점'
  and product_name in (
    'HS_한생방침향환(25%)_3.75g*60H',
    'HS_한생방침향환프리미엄_3.75g*30H'
  )
order by product_name;

